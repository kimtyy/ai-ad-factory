NEUTRAL_SHORT: Tuple[str, ...] = ("{n}, 비주얼부터 시선 강탈!", "{n}도 놓치지 마세요!", "{n}까지 곁들이면 풍성!")

# 공간 사진: 음식 문구 대신
SPACE_WORDS: Tuple[str, ...] = ("매장", "홀", "내부", "실내", "좌석", "입구", "외관", "간판", "단체석", "룸")


def profile_for(subject: str) -> Optional[Profile]:
    s = re.sub(r"\s+", "", subject or "")
    if not s:
        return None
    return next((p for p in PROFILES if p.subject.search(s)), None)


def related_words(subject: str) -> Set[str]:
    """그 사진 속 음식을 이름 없이 가리킬 때 쓰는 말 (대사에 하나라도 있으면 사진-대사 1:1로 인정). 종류를 모르면 빈 집합"""
    pr = profile_for(subject)
    return {w for w in (pr.related if pr else ()) if len(w) >= 2}


def templates(subject: str, short: bool = False) -> Tuple[str, ...]:
    """그 음식 종류에 맞는 문구만 (종류를 모르면 중립 문구). {n}에 피사체 이름을 넣어 쓴다"""
    pr = profile_for(subject)
    if pr:
        return pr.short if short else pr.long
    return NEUTRAL_SHORT if short else NEUTRAL_LONG


def pick(subject: str, index: int = 0, short: bool = False) -> str:
    """index는 같은 종류 안에서만 돌려 쓴다 (다른 종류의 형용사로 건너가지 않음). index 0 = 가장 무난한 첫 문구"""
    tpl = templates(subject, short)
    return tpl[index % len(tpl)].format(n=subject)


def is_space(subject: str) -> bool:
    return any(w in (subject or "") for w in SPACE_WORDS)
